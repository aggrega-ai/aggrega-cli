package main

import (
	"bytes"
	"fmt"
	gofmt "go/format"
	"maps"
	"slices"

	"github.com/aggrega-ai/aggrega-cli/plugins/internal/cloudimport"
)

// formNames and opNames are the names the importer's package declares for
// each form and each predicate operator.
var (
	formNames = map[cloudimport.Form]string{cloudimport.FormRaw: "FormRaw", cloudimport.FormAVM: "FormAVM",
		cloudimport.FormModule: "FormModule"}
	opNames = map[cloudimport.PredOp]string{cloudimport.OpEquals: "OpEquals", cloudimport.OpPrefix: "OpPrefix",
		cloudimport.OpContains: "OpContains", cloudimport.OpPresent: "OpPresent", cloudimport.OpAbsent: "OpAbsent"}
)

// render writes rows and the image rows as the Go source f's package embeds,
// naming revision as the revision they were read from, formatted as gofmt
// formats it. A row's traits are written ordered by label, so one set of rows
// always writes the same bytes.
func render(rows []cloudimport.Row, images []cloudimport.ImageRow, revision string, f format) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n")
	b.WriteString("// Copyright 2026 Cognitio s.r.l.\n\n")
	fmt.Fprintf(&b, "// Code generated by cloudtable from the %s Recipes of aggrega-hub and the Components and "+
		"libraries they read. DO NOT EDIT.\n\n", f.capability)
	fmt.Fprintf(&b, "package %s\n\n", f.pkg)
	b.WriteString("import \"github.com/aggrega-ai/aggrega-cli/plugins/internal/cloudimport\"\n\n")
	fmt.Fprintf(&b, "// TableRevision is the last aggrega-hub commit that changed the %s Recipes, or the\n", f.capability)
	b.WriteString("// Components and libraries they read, the generated rows were read from.\n")
	fmt.Fprintf(&b, "const TableRevision = %q\n\n", revision)
	fmt.Fprintf(&b, "// generatedRows are the mapping table's rows read from the hub's %s Recipes,\n", f.capability)
	b.WriteString("// one per Recipe whose text names its resource, ordered by key, When and\n")
	b.WriteString("// Recipe.\n")
	b.WriteString("var generatedRows = []cloudimport.Row{\n")
	for _, r := range rows {
		b.WriteString("{\n")
		writeText(&b, "Key", r.Key)
		writeText(&b, "Component", r.Component)
		writeText(&b, "Category", r.Category)
		writeText(&b, "Recipe", r.Recipe)
		if len(r.When) > 0 {
			b.WriteString("When: []cloudimport.Pred{\n")
			for _, p := range r.When {
				op, ok := opNames[p.Op]
				if !ok {
					return nil, fmt.Errorf("the row of %s tests its When with %q, which is no operator", r.Key, p.Op)
				}
				fmt.Fprintf(&b, "{Path: %s, Op: cloudimport.%s", stringsLiteral(p.Path), op)
				if p.Value != "" {
					fmt.Fprintf(&b, ", Value: %q", p.Value)
				}
				b.WriteString("},\n")
			}
			b.WriteString("},\n")
		}
		if len(r.Traits) > 0 {
			b.WriteString("Traits: map[string]string{\n")
			for _, k := range slices.Sorted(maps.Keys(r.Traits)) {
				fmt.Fprintf(&b, "%q: %q,\n", k, r.Traits[k])
			}
			b.WriteString("},\n")
		}
		if r.Form != "" {
			name, ok := formNames[r.Form]
			if !ok {
				return nil, fmt.Errorf("the row of %s is of the form %q, which is no form", r.Key, r.Form)
			}
			fmt.Fprintf(&b, "Form: cloudimport.%s,\n", name)
		}
		for _, l := range []struct {
			field string
			ps    []cloudimport.Placement
		}{{"Values", r.Values}, {"Infra", r.Infra}, {"Overrides", r.Overrides}, {"Secrets", r.Secrets},
			{"Provides", r.Provides}} {
			writePlacements(&b, l.field, l.ps)
		}
		writeText(&b, "Origin", r.Origin)
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "// generatedImages are the mapping table's container product rows read from the hub's %s\n", f.capability)
	b.WriteString("// Recipes, one per Recipe whose locals name a literal image default, ordered by repository.\n")
	b.WriteString("var generatedImages = []cloudimport.ImageRow{\n")
	for _, r := range images {
		fmt.Fprintf(&b, "{Repository: %q, Component: %q, Recipe: %q", r.Repository, r.Component, r.Recipe)
		if r.TagKey != "" {
			fmt.Fprintf(&b, ", TagKey: %q", r.TagKey)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	formatted, err := gofmt.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format the generated table: %w", err)
	}
	return formatted, nil
}

// writeText writes a text field of a row, nothing where it is empty.
func writeText(b *bytes.Buffer, field, value string) {
	if value != "" {
		fmt.Fprintf(b, "%s: %q,\n", field, value)
	}
}

// writePlacements writes a placement list of a row, nothing where it is empty;
// a placement's empty path is left out, which reads as the resource's
// identifier.
func writePlacements(b *bytes.Buffer, field string, ps []cloudimport.Placement) {
	if len(ps) == 0 {
		return
	}
	fmt.Fprintf(b, "%s: []cloudimport.Placement{\n", field)
	for _, p := range ps {
		b.WriteString("{")
		if len(p.From) > 0 {
			fmt.Fprintf(b, "From: %s, ", stringsLiteral(p.From))
		}
		fmt.Fprintf(b, "Key: %q", p.Key)
		if p.Conv != "" {
			fmt.Fprintf(b, ", Conv: %q", p.Conv)
		}
		b.WriteString("},\n")
	}
	b.WriteString("},\n")
}

// stringsLiteral writes path as a Go slice literal.
func stringsLiteral(path []string) string {
	var b bytes.Buffer
	b.WriteString("[]string{")
	for i, s := range path {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", s)
	}
	b.WriteString("}")
	return b.String()
}
