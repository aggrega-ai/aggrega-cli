#!/usr/bin/env bash
# aggrega-cli/scripts/gen-colocated-plugin-catalog.sh
#
# Lays down a fully-local, developer-owned catalog of the core plugins, with
# each guest's .wasm co-located beside its Plugin entity, so a binary that
# embeds no guests (the aggrega-light dev binary) resolves core providers,
# linters, parsers, and mutators fully offline. The full binary embeds a
# complete entity + .wasm for every core guest it embeds, so for those the
# co-located catalog serves only the light dev loop; a core plugin the binary
# does not embed (the importers) is reached by either binary only through a
# catalog, so this one carries it too.
#
# Directory layout mirrors the committed hub catalog:
#   <dir>/plugin/<socket>/<name>/<version>/plugin.yaml         the entity
#   <dir>/plugin/<socket>/<name>/<version>/<socket>--<name>.wasm  the module
# The guest's filename carries the socket as well as the name, because a bare
# name is unique only within its socket: two plugins sharing a name in different
# sockets have to reach two files. The catalog's co-located resolution tier
# derives that filename from the entity's bare-identity artifact reference and
# reads it from beside the plugin.yaml.
#
# 🔴 The filename rule has ONE home, and this script is not it: it lives beside
# the resolver that reads it, which is where a caller staging a guest asks for
# it. This script cannot ask — it runs before any binary exists to ask — so the
# flat spelling below is a second statement of that rule, and a second statement
# agreeing today is what hides tomorrow's divergence. Two things hold it shut. A
# test over this same list asserts, for every core plugin, that the flat
# spelling here is the filename the resolver reads. And the guard below refuses
# any socket or name the flat spelling is not exact for, rather than writing a
# file the resolver would never look for.
#
# The entities are the SAME bytes generated beside each guest
# (<dir>/<name>.plugin.yaml in the row's artifact directory, generated by
# gen-embedded-plugin-entities.sh), copied verbatim, so a co-located entity is
# byte-identical to the one beside its guest — for an embedded plugin, the one
# the binary embeds. The .wasm is the decompressed guest
# artifact (<name>.wasm.gz) beside it. This script therefore reuses the
# already-generated assets and runs after they are refreshed; it builds no binary
# and needs no hub overlay of its own.
#
# The output directory is auto-cleaned and regenerated on every run, and it is
# fully gitignored. It is opt-in: it perturbs no build until a developer points
# the workspace `catalog_dirs` surface at it (via `--catalog` on the light
# binary, or a local, uncommitted config overlay). A committed full-binary build
# never references it, so determinism is untouched.
#
# Usage:
#   gen-colocated-plugin-catalog.sh [output-dir]
# Default output-dir: .dev-catalog (relative to the aggrega-cli module root).
#
# Exit non-zero on the first failing step.
set -euo pipefail
cd "$(dirname "$0")/.."          # aggrega-cli module root
CLI_ROOT="$(pwd)"

DEVDIR="${1:-$CLI_ROOT/.dev-catalog}"
case "$DEVDIR" in /*) : ;; *) DEVDIR="$CLI_ROOT/$DEVDIR" ;; esac

# The core-plugin list's one reader: core_plugin_rows and the artifact directories.
. scripts/lib/core-plugins.sh
rows="$(core_plugin_rows)" || exit 1

command -v gunzip >/dev/null 2>&1 || { echo "gen-colocated-plugin-catalog: gunzip not found on PATH" >&2; exit 1; }

# entity_version reads metadata.version from a generated Plugin entity. The
# generated layout lists version directly under the metadata: block, so scoping
# to that block and taking the first version: line is exact.
entity_version() {
  awk '/^metadata:/{m=1;next} m&&/^[ ]{2}version:/{print $2;exit}' "$1"
}

# carried_verbatim reports whether the flat spelling is exact for one part of a
# guest filename — that is, whether the resolver's encoding carries every
# character of it through as authored.
#
# It admits a lowercase letter or a digit anywhere, and a hyphen only between
# two of them. It additionally refuses a hyphen followed by 'z', which the
# encoding reads as opening an escape and so writes as an escape itself. The
# condition is narrower than the encoding's own, deliberately: a part this
# refuses may still be perfectly encodable, and refusing it costs a diagnostic
# while wrongly admitting one would write a file nothing ever reads.
carried_verbatim() {
  case "$1" in *-z*) return 1;; esac
  [[ "$1" =~ ^[a-z0-9]+(-[a-z0-9]+)*$ ]]
}

# Auto-clean: remove only the generated tree root so a stale version-dir or a
# retired guest never lingers. Regenerated wholesale below.
rm -rf "$DEVDIR/plugin"

declare -a written=()
while IFS=$'\x1f' read -r socket name sourcePath toolchain extraRoots embed dir; do
  [ -n "$socket" ] || continue
  entity="$dir/$name.plugin.yaml"
  wasmgz="$dir/$name.wasm.gz"
  if [ ! -f "$entity" ]; then
    echo "gen-colocated-plugin-catalog: missing core plugin entity $entity (run gen-embedded-plugin-entities.sh first)" >&2
    exit 1
  fi
  if [ ! -f "$wasmgz" ]; then
    echo "gen-colocated-plugin-catalog: missing core guest $wasmgz (run build-embedded-plugins.sh first)" >&2
    exit 1
  fi
  ver="$(entity_version "$entity")"
  if [ -z "$ver" ]; then
    echo "gen-colocated-plugin-catalog: could not read metadata.version from $entity" >&2
    exit 1
  fi
  if ! carried_verbatim "$socket" || ! carried_verbatim "$name"; then
    echo "gen-colocated-plugin-catalog: plugin $socket/$name needs a guest filename this script cannot spell." >&2
    echo "  The resolver encodes a socket or name outside lowercase letters, digits and separating hyphens," >&2
    echo "  so the flat <socket>--<name>.wasm spelling here would name a file it never reads." >&2
    echo "  Derive the filename from the resolver's own mapping instead of extending the spelling here." >&2
    exit 1
  fi
  target="$DEVDIR/plugin/$socket/$name/$ver"
  mkdir -p "$target"
  cp "$entity" "$target/plugin.yaml"
  gunzip -c "$wasmgz" > "$target/$socket--$name.wasm"
  written+=("$socket/$name")
done <<< "$rows"

echo "=== wrote co-located plugin catalog to $DEVDIR/plugin: ${written[*]} ==="
