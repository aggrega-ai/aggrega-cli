#!/usr/bin/env bash
# aggrega-cli/scripts/gen-colocated-plugin-catalog.sh
#
# Lays down a fully-local, developer-owned catalog of the core plugins, with
# each guest's .wasm co-located beside its Plugin entity, so a binary that
# embeds no guests (the aggrega-light dev binary) resolves core providers,
# linters, parsers, and mutators fully offline. The full binary never needs
# this — it embeds a complete entity + .wasm for every core guest — so the
# co-located catalog exists only for the light dev loop.
#
# Layout mirrors the unpacked OCI artifact and the committed hub catalog:
#   <dir>/plugin/<socket>/<name>/<version>/plugin.yaml   the entity
#   <dir>/plugin/<socket>/<name>/<version>/<name>.wasm   the module beside it
# The catalog's co-located resolution tier reads <name>.wasm from beside its
# plugin.yaml, keyed by the entity's bare-identity artifact reference.
#
# The entities are the SAME bytes the full binary embeds
# (internal/wasm/embedded/plugins/<name>.plugin.yaml, generated by
# gen-embedded-plugin-entities.sh), copied verbatim, so a co-located entity is
# byte-identical to its embedded twin. The .wasm is the decompressed embedded
# guest artifact (<name>.wasm.gz). This script therefore reuses the
# already-generated embed assets and runs after they are refreshed; it builds no
# binary and needs no hub overlay of its own.
#
# The output directory is auto-cleaned and regenerated on every run, and it is
# fully gitignored. It is opt-in: it perturbs no build until a developer points
# the workspace `catalog_dirs` surface at it (via `--catalog` on the light
# binary, or a local, uncommitted config overlay). A committed full-binary build
# never references it, so determinism is untouched.
#
# Usage:
#   gen-colocated-plugin-catalog.sh [output-dir]
# Default output-dir: .dev-catalog (relative to the aggrega-cli module root).
#
# Exit non-zero on the first failing step.
set -euo pipefail
cd "$(dirname "$0")/.."          # aggrega-cli module root
CLI_ROOT="$(pwd)"

DEVDIR="${1:-$CLI_ROOT/.dev-catalog}"
case "$DEVDIR" in /*) : ;; *) DEVDIR="$CLI_ROOT/$DEVDIR" ;; esac

MANIFEST="internal/wasm/embedded/embedded-plugins.tsv"
EMBED_DIR="internal/wasm/embedded/plugins"
[ -f "$MANIFEST" ] || { echo "gen-colocated-plugin-catalog: manifest not found: $MANIFEST" >&2; exit 1; }

command -v gunzip >/dev/null 2>&1 || { echo "gen-colocated-plugin-catalog: gunzip not found on PATH" >&2; exit 1; }

# entity_version reads metadata.version from a generated Plugin entity. The
# generated layout lists version directly under the metadata: block, so scoping
# to that block and taking the first version: line is exact.
entity_version() {
  awk '/^metadata:/{m=1;next} m&&/^[ ]{2}version:/{print $2;exit}' "$1"
}

# Auto-clean: remove only the generated tree root so a stale version-dir or a
# retired guest never lingers. Regenerated wholesale below.
rm -rf "$DEVDIR/plugin"

declare -a written=()
while IFS=$'\t' read -r socket name sourcePath toolchain extraRoots; do
  case "$socket" in ''|'#'*) continue;; esac
  entity="$EMBED_DIR/$name.plugin.yaml"
  wasmgz="$EMBED_DIR/$name.wasm.gz"
  if [ ! -f "$entity" ]; then
    echo "gen-colocated-plugin-catalog: missing embedded entity $entity (run gen-embedded-plugin-entities.sh first)" >&2
    exit 1
  fi
  if [ ! -f "$wasmgz" ]; then
    echo "gen-colocated-plugin-catalog: missing embedded guest $wasmgz (run build-embedded-plugins.sh first)" >&2
    exit 1
  fi
  ver="$(entity_version "$entity")"
  if [ -z "$ver" ]; then
    echo "gen-colocated-plugin-catalog: could not read metadata.version from $entity" >&2
    exit 1
  fi
  target="$DEVDIR/plugin/$socket/$name/$ver"
  mkdir -p "$target"
  cp "$entity" "$target/plugin.yaml"
  gunzip -c "$wasmgz" > "$target/$name.wasm"
  written+=("$socket/$name")
done < "$MANIFEST"

echo "=== wrote co-located plugin catalog to $DEVDIR/plugin: ${written[*]} ==="
