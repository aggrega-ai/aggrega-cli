// The order-keeping container, one realization per guest binding language.
//
// A map whose order is part of what it carries needs a container that keeps the
// order it was filled in, and none of the three binding languages supplies one
// that also reads and writes the wire's JSON form in that order. Go's built-in
// map iterates in an unspecified order and Rust's standard maps in hash or key
// order; a TypeScript Map keeps insertion order, but JSON.parse lists a key that
// is an array index ahead of every other key before any code sees the object. So
// each binding carries its own, and each target below emits one language's
// container whole. Like the shared CBOR helpers, the targets read no schema.
//
// The three are kept side by side because they are one contract in three
// languages: insertion order kept; a key set again keeping its position and
// taking the new value; lookup by hash; a JSON object read and written in the
// map's order; and a repeated key refused, naming the key, with the same
// sentence everywhere.
//
// Each also carries the unpublished entry point a decoder builds a map through,
// refusing a repeated key as it goes: an unexported method in Go, a crate-private
// method in Rust, and in TypeScript a module the package entry does not
// re-export. The binding's own JSON decode uses it, and so does the generated
// Rust decode of the binary form. The Go container words its refusal through the
// repeated-key error the package's shared CBOR helpers declare, which the
// generated Go decode of the binary form returns too, so in each language the
// two encodings refuse a repeat alike.

// schemaFreeGenHeader is the provenance header of a generated file that reads no
// schema. The comment syntax is shared by the three binding languages, so one
// header serves them all.
const schemaFreeGenHeader = "// SPDX-License-Identifier: Apache-2.0\n// Copyright 2026 Cognitio S.r.l.\n\n" +
	"// Code generated by internal/tools/typegen. DO NOT EDIT.\n" +
	"// Regenerate with `go generate ./internal/tools/typegen` from the\n// aggrega-cli checkout.\n\n"

// generateGoOrderedMap produces the Go binding's orderedmap_gen.go: the
// order-keeping container and its JSON codec. It references the streaming JSON
// helpers and the repeated-key error the package's helpers-bearing codec file
// declares, as every other codec file in the package does.
func generateGoOrderedMap(t codecTarget) ([]byte, error) {
	return formatSource(schemaFreeGenHeader+"package "+t.pkg+"\n\n", goOrderedMapSrc)
}

// generateRustOrderedMap produces the Rust binding's orderedmap_gen.rs. The crate
// declares the module privately and re-exports its public items, so the
// crate-private entry point stays unpublished.
func generateRustOrderedMap(t codecTarget) ([]byte, error) {
	return []byte(schemaFreeGenHeader + rustOrderedMapSrc), nil
}

// generateTSOrderedMap produces the TypeScript binding's orderedmap_gen.ts: the
