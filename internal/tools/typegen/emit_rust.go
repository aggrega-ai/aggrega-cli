// generateDefsRust produces the Rust source for a multi-type codec crate module:
// one serde-derive struct per `$defs` entry (in declared order). The wire codec
// is serde_json itself; the generated code shapes the types so serde_json's
// output is byte-identical to the Go reflect-free codec:
//
//   - map fields use BTreeMap so serde_json serializes keys in sorted order,
//     matching the Go codec's sort.Strings(keys) determinism;
//   - opaque (`any` / json.RawMessage) values carry as Box<RawValue> so the
//     original bytes pass through verbatim, never re-sorted;
//   - non-required fields carry #[serde(default, skip_serializing_if = ...)] so
//     an empty value is omitted, matching Go omitempty;
//   - struct fields emit in schema property-declaration order;
//   - a field whose Rust name collides with a keyword (e.g. type) uses the raw
//     identifier form (r#type) with #[serde(rename)] to keep the wire key.
//
// The top-level `oneOf` is ignored — the walk reads `$defs` only. The target's
// vocabulary rewrites x-aggrega-go-type values (host spelling → guest spelling)
// before the Go→Rust type translation.
func generateDefsRust(t codecTarget) ([]byte, error) {
	root, err := decodeNode([]byte(t.schema))
	if err != nil {
		return nil, fmt.Errorf("decode schema: %w", err)
	}
	if len(root.defs) == 0 {
		return nil, fmt.Errorf("schema %s has no $defs to emit", t.schemaFile)
	}

	// The module declares each `$defs` entry AND each object those entries state
	// inline. An inline object is named after the type declaring it and a field
	// typed as one carries that name, so a module emitting only the entries
	// publishes a struct field naming a type the module never declares.
	defs := expandInlineObjects(root.defs)

	defTypes := map[string]bool{}
	for _, d := range defs {
		defTypes[d.name] = true
	}
	// externalDefTypes are emitted by a sibling codec target into the same crate;
	// treat them as def types so a field annotated with one resolves to the type
	// (not an opaque carrier), and import them from the crate root below.
	for _, ext := range t.externalDefTypes {
		defTypes[ext] = true
	}

	// Compute, for every def type, whether its struct derives Default — in a
	// pre-pass over all defs so a field can consult the defaultability of a type
	// emitted later in the file (a forward reference within the same module, e.g.
	// LinterInput's policies field referencing the Policies struct below it). This
	// is the single source of the Default-derive predicate: emitRustStruct reads
	// it to decide its own derive, and rustSerdeAttrs reads it to decide whether a
	// non-required nested-struct field may carry #[serde(default)] (which requires
	// the referenced type to implement Default).
	defaultableTypes := map[string]bool{}
	for _, d := range defs {
		defaultableTypes[d.name] = rustDefDefaultable(d.name, d.node, t.vocabulary, defTypes)
	}

	// Emit the structs into a temporary buffer first so the import block can
	// declare only the items the generated code actually references (an unused
	// `use` is a Rust warning).
	var structs strings.Builder
	for _, d := range defs {
		emitRustStruct(&structs, d.name, d.node, t.vocabulary, defTypes, defaultableTypes)
	}
	// The canonical-CBOR codec impls, parallel to the serde structs, for a guest
	// target. Appended after the structs; they reference the shared cbor_gen
	// module as crate::cbor_gen::* and add no new imports beyond BTreeMap (which a
	// map-bearing struct already declares).
	if t.emitsCBOR() {
		structs.WriteString("\n")
		for _, d := range defs {
			emitRustCBOR(&structs, d.name, d.node, t.vocabulary, defTypes)
		}
	}
	structSrc := structs.String()

	var body strings.Builder
	body.WriteString("// SPDX-License-Identifier: Apache-2.0\n// Copyright 2026 Cognitio S.r.l.\n\n")
	fmt.Fprintf(&body, "// Code generated by internal/tools/typegen from\n// aggrega-schemas/json/%s. DO NOT EDIT.\n", t.schemaFile)
	body.WriteString("// Regenerate with `go generate ./internal/tools/typegen` from the\n// aggrega-cli checkout.\n\n")
	body.WriteString("use serde::{Deserialize, Serialize};\n")
	if strings.Contains(structSrc, "RawValue") {
		body.WriteString("use serde_json::value::RawValue;\n")
	}
	if strings.Contains(structSrc, "BTreeMap<") {
		body.WriteString("use std::collections::BTreeMap;\n")
	}
	// A field typed as a sibling-codec type (externalDefTypes) imports it from the
	// crate root, where lib.rs re-exports every generated module's types.
	for _, ext := range t.externalDefTypes {
		if strings.Contains(structSrc, ext) {
			fmt.Fprintf(&body, "use crate::%s;\n", ext)
		}
	}
	body.WriteString("\n")
	// is_default omits a scalar at its zero value on serialize, matching Go
	// omitempty on a scalar field. Emitted only when a field references it.
	if strings.Contains(structSrc, "is_default") {
		body.WriteString("fn is_default<T: Default + PartialEq>(v: &T) -> bool {\n")
		body.WriteString("    *v == T::default()\n")
		body.WriteString("}\n\n")
	}
	// serialize_f64 renders an integer-valued finite f64 within i64 range as a
	// bare integer (serialize_i64), so the wire matches the Go and TS codecs
	// byte-for-byte; every other value (fractional, or out of i64 range) falls
	// through to the default f64 serialization, which already matches. Emitted
	// only when a field references it.
	if strings.Contains(structSrc, "serialize_f64") {
		body.WriteString(`fn serialize_f64<S>(v: &f64, s: S) -> Result<S::Ok, S::Error>
where
    S: serde::Serializer,
{
    if v.is_finite() && v.fract() == 0.0 && *v >= i64::MIN as f64 && *v <= i64::MAX as f64 {
        s.serialize_i64(*v as i64)
    } else {
        s.serialize_f64(*v)
    }
}

`)
	}
	body.WriteString(structSrc)

	return []byte(body.String()), nil
}

// rustDefDefaultable reports whether the struct emitted for a def node derives
// Default. A struct derives Default unless it carries a required opaque field —
// a bare Box<RawValue> (json.RawMessage / any), which has no Default impl. This
// is the single predicate behind both the Default derive on the struct and the
// per-field decision to emit #[serde(default)] on a non-required nested-struct
// field that references the type; keeping it in one function prevents the two
// from diverging.
func rustDefDefaultable(typeName string, n schemaNode, vocab map[string]string, defTypes map[string]bool) bool {
	for _, f := range resolveCodecFields(typeName, n, vocab) {
		if rustFieldType(f, defTypes) == "Box<RawValue>" {
			return false
		}
	}
	return true
}

// emitRustStruct writes one serde-derive struct for a def node. defaultableTypes
// maps every def type name in the module to whether its struct derives Default,
// computed in a pre-pass so a field's serde attributes can consult the
// defaultability of a type emitted later in the same module.
func emitRustStruct(b *strings.Builder, typeName string, n schemaNode, vocab map[string]string, defTypes map[string]bool, defaultableTypes map[string]bool) {
	fields := resolveCodecFields(typeName, n, vocab)
	if n.Description != "" {
		writeRustDoc(b, "", oneLine(n.Description))
	}
	// Debug + Clone are universally derivable (Box<RawValue> supports both) and
	// useful to plugin authors. PartialEq is omitted: serde_json::value::RawValue
	// (the verbatim-opaque carrier) does not implement it, so a blanket PartialEq
	// derive would not compile for any type carrying an opaque field. A wire-parity
	// check compares serialized bytes rather than struct equality. Default is
	// derived only when every field is Default-able — a non-optional Box<RawValue>
	// (a required opaque field) is not, so a type carrying one omits Default.
	rustTypes := make([]string, len(fields))
	for i, f := range fields {
		rustTypes[i] = rustFieldType(f, defTypes)
	}
	if defaultableTypes[typeName] {
		b.WriteString("#[derive(Debug, Clone, Default, Serialize, Deserialize)]\n")
	} else {
		b.WriteString("#[derive(Debug, Clone, Serialize, Deserialize)]\n")
	}
	fmt.Fprintf(b, "pub struct %s {\n", typeName)
	for i, f := range fields {
		rustTy := rustTypes[i]
		name, renamed := rustFieldName(f.key)
		if f.desc != "" {
			writeRustDoc(b, "    ", oneLine(f.desc))
		}
		attrs := rustSerdeAttrs(f, rustTy, renamed, defaultableTypes)
		for _, a := range attrs {
			fmt.Fprintf(b, "    %s\n", a)
		}
		fmt.Fprintf(b, "    pub %s: %s,\n", name, rustTy)
	}
	b.WriteString("}\n\n")
}

// rustFieldType resolves a field's Rust type, accounting for optionality. A
// non-required opaque value (json.RawMessage / any) has no native empty form, so
// it wraps in Option<Box<RawValue>> and is omitted when None — matching the Go
// codec's omit-when-empty on a json.RawMessage field. Every other shape carries
// its own empty notion (String::is_empty, Vec::is_empty, BTreeMap::is_empty) or
// is a struct value (always emitted, matching Go's omitempty no-op on a struct),
// so it uses the plain translation.
func rustFieldType(f codecField, defTypes map[string]bool) string {
	base := goTypeToRust(f.goType, "", defTypes)
	if !f.required && isRustOpaque(base) {
		return "Option<" + base + ">"
	}
	return base
}

// isRustOpaque reports whether a Rust type is the verbatim-opaque carrier.
func isRustOpaque(rustTy string) bool {
	return rustTy == "Box<RawValue>"
}

// rustSerdeAttrs builds the #[serde(...)] attribute lines for one field: a
// rename when the wire key differs from the Rust identifier, and a
// default (with skip_serializing_if where a skip predicate exists) for
// non-required fields so a missing field decodes to the zero value and an empty
// value is omitted on serialize (matching Go omitempty).
func rustSerdeAttrs(f codecField, rustTy string, renamed bool, defaultableTypes map[string]bool) []string {
	var inner []string
	if renamed {
		inner = append(inner, fmt.Sprintf("rename = %q", f.key))
	}
	if !f.required {
		// A non-required field with an omit notion (a scalar, collection, opaque,
		// or pointer — anything with a skip predicate) gets default + the predicate
		// so it decodes from a missing field to its zero value and serializes only
		// when non-empty, matching the Go codec's omitempty.
		//
		// A predicate-less non-required field is a bare nested struct: Go's
		// omitempty is a no-op on a struct value, so a struct-typed *guest* field
		// would always be present. But a host twin may realize the same field as an
		// opaque, omittable payload (a json.RawMessage with omitempty that the host
		// assembles dynamically) and so OMIT it when empty — and the guest must
		// then tolerate the missing field rather than fail with "missing field". So
		// the guest emits a bare #[serde(default)] (no skip_serializing_if: a
		// struct has no "empty" predicate) whenever the referenced type derives
		// Default, giving deserialize tolerance while keeping serialize behavior.
		// A nested-struct type that does NOT derive Default (it carries a required
		// Box<RawValue>) cannot take #[serde(default)] — it would not compile — so
		// it is left bare; a host that omits such a field would break the guest,
		// but no such non-required field exists today.
		if skip := rustSkipPredicate(rustTy); skip != "" {
			inner = append(inner, "default", fmt.Sprintf("skip_serializing_if = %q", skip))
		} else if defaultableTypes[rustTy] {
			inner = append(inner, "default")
		}
	}
	// An f64 field carries a canonical serializer so an integer-valued finite
	// f64 emits as a bare integer (e.g. 1, not 1.0), matching the Go and TS
	// codecs byte-for-byte. Applied to both required and non-required f64 fields
	// (hence before the empty-inner early return), so a required f64 gains the
	// attribute on its own and a non-required f64 gains it alongside its
	// default/skip pair.
	if rustTy == "f64" {
		inner = append(inner, `serialize_with = "serialize_f64"`)
	}
	if len(inner) == 0 {
		return nil
	}
	return []string{fmt.Sprintf("#[serde(%s)]", strings.Join(inner, ", "))}
}

// rustSkipPredicate returns the skip_serializing_if predicate path for a Rust
// type so an empty value is omitted, matching Go omitempty. An empty string
// means the type carries no omit notion at this layer (e.g. a required-by-shape
// nested struct).
func rustSkipPredicate(rustTy string) string {
	switch {
	case rustTy == "String":
		return "String::is_empty"
	case rustTy == "bool" || rustTy == "i64" || rustTy == "f64":
		// Omit the zero value, matching Go omitempty on a scalar. is_default is a
		// generated module helper (emitted when any field uses it).
		return "is_default"
	case strings.HasPrefix(rustTy, "BTreeMap<"):
		return "BTreeMap::is_empty"
	case strings.HasPrefix(rustTy, "Vec<"):
		return "Vec::is_empty"
	case strings.HasPrefix(rustTy, "Option<"):
		return "Option::is_none"
	default:
		return ""
	}
}

// goTypeToRust translates a resolved Go-vocabulary type string (the same
// spelling the Go backend consumes) into the equivalent Rust type. The
// vocabulary has already rewritten host spellings to guest spellings
// (map[string]X, json.RawMessage, scalars); this function maps those to Rust.
//
//   - map[string]V → BTreeMap<String, RustV> (sorted-key serialize)
//   - []V          → Vec<RustV>
//   - json.RawMessage / any / interface{} → Box<RawValue> (verbatim opaque)
//   - *T (pointer to a def type) → Option<Box<T>> (recursive cycle break)
//   - string/bool/int → String/bool/i64
//   - a def type name → itself
func goTypeToRust(goType, _ string, defTypes map[string]bool) string {
	switch {
	case goType == "string":
		return "String"
	case goType == "bool":
		return "bool"
	case goType == "int" || goType == "int64":
		return "i64"
	case goType == "float64":
		return "f64"
	case goType == "[]byte":
		// encoding/json emits []byte as a base64 string; serde_bytes is not
		// wired, so carry as a String of base64 to match the wire. The Go
		// guest codec base64-encodes; a Rust guest reads the base64 string.
		return "String"
	case goType == "json.RawMessage" || goType == "any" || goType == "interface{}":
		return "Box<RawValue>"
	case strings.HasPrefix(goType, "map["):
		valType := goType[strings.IndexByte(goType, ']')+1:]
		return "BTreeMap<String, " + goTypeToRust(valType, "", defTypes) + ">"
	case strings.HasPrefix(goType, "[]"):
		return "Vec<" + goTypeToRust(goType[2:], "", defTypes) + ">"
	case strings.HasPrefix(goType, "*"):
		elem := goType[1:]
		switch elem {
		case "string", "bool", "int", "int64", "float64", "[]byte":
			// A pointer to a scalar models a present-or-absent scalar (a nil
			// pointer is omitted; a pointer to the zero value is still emitted),
			// so it maps to Option<scalar> — not the opaque carrier.
			return "Option<" + goTypeToRust(elem, "", defTypes) + ">"
		}
		if defTypes[elem] {
			return "Option<Box<" + elem + ">>"
		}
		return "Option<Box<RawValue>>"
	default:
		// A def type name. A bare recursive self-reference cannot be detected
		// here without the parent context; recursion through a def appears as a
		// map/Vec/pointer field in practice (Box already applied), so a direct
		// def field is non-recursive and needs no Box.
		return goType
	}
}

var rustKeywords = map[string]bool{
	"type": true, "as": true, "use": true, "fn": true, "let": true, "mut": true,
	"ref": true, "self": true, "super": true, "crate": true, "move": true,
	"impl": true, "trait": true, "struct": true, "enum": true, "match": true,
	"in": true, "if": true, "else": true, "loop": true, "while": true, "for": true,
	"mod": true, "pub": true, "return": true, "where": true, "const": true,
}

// rustFieldName maps a JSON wire key to a Rust struct field name and reports
// whether a #[serde(rename)] is needed to preserve the wire key. Most wire keys
// are snake_case (the Rust idiom) and pass through verbatim. Two cases need a
// rename so the wire key is preserved while the Rust identifier stays idiomatic:
//   - a key that is a Rust keyword takes the raw-identifier form (r#type), and
//     the rename keeps the wire key "type" (r#type would otherwise be fine, but
//     the rename is harmless and explicit);
//   - a camelCase key (e.g. apiVersion) converts to snake_case (api_version),
//     and the rename preserves the camelCase wire key.
func rustFieldName(key string) (string, bool) {
	if rustKeywords[key] {
		return "r#" + key, true
	}
	if snake := camelToSnake(key); snake != key {
		return snake, true
	}
	return key, false
}

// camelToSnake converts a camelCase identifier to snake_case. A key with no
// interior uppercase letter (already snake_case or all-lowercase) is returned
// unchanged.
func camelToSnake(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c >= 'A' && c <= 'Z' {
			if i > 0 {
				b.WriteByte('_')
			}
			b.WriteByte(c - 'A' + 'a')
		} else {
			b.WriteByte(c)
		}
	}
	return b.String()
}

// writeRustDoc writes a /// doc line at the given indent.
func writeRustDoc(b *strings.Builder, indent, doc string) {
	fmt.Fprintf(b, "%s/// %s\n", indent, doc)
}
