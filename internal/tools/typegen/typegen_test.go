// TestTargetPathsNameRegisteredTargets checks the two path tables in the
// direction the drift gates cannot. Each of those gates walks a target registry
// and looks the target's path up, so a registered target with no path fails
// loudly — but a path entry naming a target that is no longer registered is
// never looked up by anything, and so reports nothing at all. Removing a target
// from its registry leaves its path entry behind, still pointing across the
// submodule boundary at a file nothing generates, and every gate stays green.
//
// These tables are where a coupling that appears in no repository's diff is
// written down: the generator reads a schema in one repository and commits its
// output into another. A stale entry here is a stale record of that coupling, so
// the two directions are asserted rather than one.
func TestTargetPathsNameRegisteredTargets(t *testing.T) {
	for outFile := range enumTargetPaths {
		if _, ok := enumSources[outFile]; !ok {
			t.Errorf("enumTargetPaths registers a committed path for %q, which is not a registered enum "+
				"target: nothing generates that file, so the entry is inert and no gate reads it", outFile)
		}
	}
	for outFile := range codecTargetPaths {
		if _, ok := codecTargets[outFile]; !ok {
			t.Errorf("codecTargetPaths registers a committed path for %q, which is not a registered codec "+
				"target: nothing generates that file, so the entry is inert and no gate reads it", outFile)
		}
	}
}

// TestRegenClean_Codec is the regen-drift gate for the multi-type codec
// targets: re-running the generator for each codec target must byte-match the
// committed generated file. A failure means the schema or the generator changed
// without regenerating.
//
// It names the remedy per target rather than prescribing one command for all of
// them, because the batch command does not reach every registered target: a
// minority carry no directive naming them, and for those it exits zero and
// changes nothing. A red gate whose prescribed fix reports success and fixes
// nothing teaches the reader that the gate is broken rather than that the tree
// is, so the per-target remedy is derived from the directives themselves and
// cannot drift from them.
//
// This extends the entity regen-drift contract to the codec spine so the
// reflect-free codec self-verifies determinism alongside the entity types.
func TestRegenClean_Codec(t *testing.T) {
	driven := regenDirectiveTargets(t)
	for outFile := range codecTargets {
		t.Run(outFile, func(t *testing.T) {
			got, err := generateFor(outFile)
			if err != nil {
				t.Fatalf("generate codec %s: %v", outFile, err)
			}
			dir, ok := codecTargetPaths[outFile]
			if !ok {
				t.Fatalf("no committed path registered for codec target %q", outFile)
			}
			path := filepath.Join(append(append([]string{}, dir...), outFile)...)
			want, err := os.ReadFile(path)
			if err != nil {
				t.Fatalf("read committed %s: %v", path, err)
			}
			if string(got) != string(want) {
				t.Errorf("%s is stale: generator output differs from the committed file.\n%s",
					outFile, regenRemedyFor(path, driven[outFile]))
			}
		})
	}
}

// regenDirectiveTargets returns the set of output basenames the generate
// directives declared in this package name. The batch command runs exactly this
// package's directives, so this set is that command's whole reach — and a
// registered target outside it is regenerated by no batch command at all.
//
// The set is read from the source rather than restated as a list, so a directive
// added or removed later changes the remedy this gate prints with no second edit.
// A hand-kept list would agree on the day it was written and mislead afterwards,
// which is the failure this gate's remedy already had once.
func regenDirectiveTargets(t *testing.T) map[string]bool {
	t.Helper()
	const prefix = "//go:generate "
	entries, err := os.ReadDir(".")
	if err != nil {
		t.Fatalf("read this package's directory: %v", err)
	}
	named := map[string]bool{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		body, err := os.ReadFile(e.Name())
		if err != nil {
			t.Fatalf("read %s: %v", e.Name(), err)
		}
		for _, line := range strings.Split(string(body), "\n") {
			// Column zero only, matching the toolchain's own rule: an indented
			// line that looks like a directive is a comment and runs nothing.
			if !strings.HasPrefix(line, prefix) {
				continue
			}
			fields := strings.Fields(strings.TrimRight(line, "\r"))
			named[filepath.Base(fields[len(fields)-1])] = true
		}
	}
	// A pass over an empty set would silently tell every failing target that no
	// directive names it, which is the wrong instruction stated confidently.
	if len(named) == 0 {
		t.Fatal("no generate directive was found in this package, so the remedy this gate prints could not be derived")
	}
	return named
}

// regenRemedyFor names what actually regenerates one registered codec target.
// committedPath is that target's path relative to this package; driven reports
// whether a directive in this package names it.
//
// The single-target invocation is given first because it is correct for every
// target: the generator writes exactly the file named as its argument. The batch
// command is named second, with its reach stated honestly — for a target no
// directive names, running it exits zero and leaves the file stale, which is why
// the two cases are worded as opposites rather than sharing one line.
func regenRemedyFor(committedPath string, driven bool) string {
	fromModuleRoot := filepath.Join("internal", "tools", "typegen", committedPath)
	remedy := "Regenerate it from the aggrega-cli module root with `go run ./internal/tools/typegen " +
		fromModuleRoot + "`, then commit the result."
	if driven {
		return remedy + "\nThe batch command `go generate ./internal/tools/typegen/...` regenerates this " +
			"target too, along with every other target a directive in that package names."
	}
	return remedy + "\nNo generate directive names this target, so `go generate ./internal/tools/typegen/...` " +
		"does NOT regenerate it: that command exits zero and leaves this file exactly as stale as it was."
}

// subjectSchemaKind reports whether a schema kind token names a contract a Wasm
// guest speaks, and so owes a generated type in every binding language. Two
// shapes qualify: a socket payload, whose kind token is prefixed "wasm-", and
// the IR graph, whose kind token is "ir". Every other embedded schema describes
// an authoring surface only the host reads — a Component, a Release, the
// lockfile — so no guest binding is owed for it.
func subjectSchemaKind(kind string) bool {
	return strings.HasPrefix(kind, "wasm-") || kind == "ir"
}

// bindingLanguageByExt names the three languages a plugin development kit ships,
// keyed by the file extension the generator emits for each. A subject schema
// owes a target in all three: a socket contract bound in Go alone leaves the
// Rust and TypeScript kits without the type, and a guest author hand-rolling
// JSON against a wire format nothing generates for them.
var bindingLanguageByExt = map[string]string{
	".go": "Go",
	".rs": "Rust",
	".ts": "TypeScript",
}

// bindingLanguages lists those languages in a fixed order, so a failure reports
// the missing set deterministically rather than in map order.
var bindingLanguages = []string{"Go", "Rust", "TypeScript"}

// generatorTables names the tables searched for a subject schema's targets, in a
// fixed order for the same reason. Both are searched because the property is a
// union over them: a schema's three bindings may arrive as codecs, as string-enum
// constant emissions, or as a mix, and which of those a payload gets is a choice
// about its shape rather than a statement about whether the guest is served.
var generatorTables = []string{"codecTargets", "enumSources"}

// goOnlySubjectKinds names any subject schema deliberately bound in Go alone,
// mapped to the reason it is exempt. A member must be a payload no guest ever
// encodes or decodes; "not bound yet" does not qualify, because that is exactly
// the state the assertion below exists to report. It is empty: every subject
// schema shipped today carries all three bindings.
var goOnlySubjectKinds = map[string]string{}

// TestBindingsCoverEverySubjectSchema closes the hole the regen-drift gates
// above leave open. Each of those walks a generator table and byte-compares what
// is declared, so all of them are structurally blind to a schema with no target
// at all: a socket payload could ship bound in Go only, and TestRegenClean_Codec
// and TestRegenClean_Enums would both stay green. This asserts the property they
// cannot see — every socket payload and the IR graph carry a Go, a Rust and a
// TypeScript target — and asserts it over both tables at once, because the two
// hold different halves of one guarantee.
//
// The schema population is read from the embedded schema tree, so a schema added
// to the distribution enters this assertion without anyone remembering to add it
// here. Enumerating from a second hand list would make the assertion
// self-referential and it would prove nothing.
func TestBindingsCoverEverySubjectSchema(t *testing.T) {
	// A target is attributed to a schema by the bytes it is generated from
	// rather than by the file name recorded beside them. The bytes are the real
	// dependency, and reading them needs no second copy of the schema-file
	// naming convention, whose sole home is the schema package. The shared
	// CBOR-helper targets are generated from no schema at all, so their empty
	// bytes match no kind and they fall out here instead of faulting.
	kindBySchema := map[string]string{}
	for _, kind := range schemas.Kinds() {
		body, ok := schemas.SchemaByKind(kind)
		if !ok {
			t.Fatalf("kind %q is enumerated but its schema does not resolve", kind)
		}
		if prior, dup := kindBySchema[body]; dup {
			t.Fatalf("kinds %q and %q hold byte-identical schemas, so a generator "+
				"target cannot be attributed to either", prior, kind)
		}
		kindBySchema[body] = kind
	}

	type binding struct {
		langs  map[string]bool
		tables map[string]bool
	}
	found := map[string]*binding{}
	record := func(table, outFile, schemaBody string) {
		kind, ok := kindBySchema[schemaBody]
		if !ok {
			return
		}
		b := found[kind]
		if b == nil {
			b = &binding{langs: map[string]bool{}, tables: map[string]bool{}}
			found[kind] = b
		}
		b.tables[table] = true
		if lang, ok := bindingLanguageByExt[filepath.Ext(outFile)]; ok {
			b.langs[lang] = true
		}
	}
	for outFile, tgt := range codecTargets {
		record("codecTargets", outFile, tgt.schema)
	}
	for outFile, src := range enumSources {
		record("enumSources", outFile, src.schema)
	}

	missingLangs := func(b *binding) []string {
		var missing []string
		for _, lang := range bindingLanguages {
			if b == nil || !b.langs[lang] {
				missing = append(missing, lang)
			}
		}
		return missing
	}
	// The table names go into the failure message so it points at where to look:
	// a schema short one language is fixed in whichever table already holds its
	// other targets, and a schema found in neither table is a different problem
	// from one found in a table but bound in fewer languages.
	tablesHolding := func(b *binding) string {
		if b == nil || len(b.tables) == 0 {
			return "neither generator table"
		}
		var names []string
		for _, table := range generatorTables {
			if b.tables[table] {
				names = append(names, table)
			}
		}
		return strings.Join(names, " and ")
	}

	var subjectKinds []string
	for _, kind := range schemas.Kinds() {
		if subjectSchemaKind(kind) {
			subjectKinds = append(subjectKinds, kind)
		}
	}
	// A pass over an empty population certifies nothing, so it is a failure
	// rather than a green: an embed that stopped resolving, or a criterion that
	// stopped matching, must not read as "every subject schema is bound".
	if len(subjectKinds) == 0 {
		t.Fatalf("no subject schema was enumerated out of %d embedded kinds, so this "+
			"assertion checked nothing: either the embedded schema tree is empty or "+
			"subjectSchemaKind no longer matches any shipped kind", len(kindBySchema))
	}
	isSubject := make(map[string]bool, len(subjectKinds))
	for _, kind := range subjectKinds {
		isSubject[kind] = true
	}

	for _, kind := range subjectKinds {
		if _, exempt := goOnlySubjectKinds[kind]; exempt {
			continue
		}
		missing := missingLangs(found[kind])
		if len(missing) == 0 {
			continue
		}
		t.Errorf("schema %q has no %s target, so a plugin development kit in %s ships "+
			"without its type; the targets it does have are registered in %s. Register "+
			"a target per missing language in codecTargets or enumSources, or, if no "+
			"guest ever encodes or decodes this payload, name the schema in "+
			"goOnlySubjectKinds with the reason.",
			kind, strings.Join(missing, "/"), strings.Join(missing, " and "), tablesHolding(found[kind]))
	}

	// The exemption set is walked in the reverse direction too, so it cannot rot
	// unnoticed: a member naming a schema that no longer ships silently exempts
	// nothing, and a member that in fact carries every binding misdescribes the
	// tree it is meant to explain.
	for kind, reason := range goOnlySubjectKinds {
		if !isSubject[kind] {
			t.Errorf("goOnlySubjectKinds names %q (%s), which is not an enumerated "+
				"subject schema, so the exemption is stale and exempts nothing", kind, reason)
			continue
		}
		if len(missingLangs(found[kind])) == 0 {
			t.Errorf("goOnlySubjectKinds names %q (%s), but it carries every binding "+
				"language, so the exemption misdescribes the tree and should be removed", kind, reason)
		}
	}
}

// schemaFileSuffix is the tail every distributed schema file carries, used here
// for one purpose: an entry records a file NAME while the schema package's
// dynamic lookup is keyed by the file STEM, so the name is trimmed back to the
// kind token before it is looked up.
//
// It is deliberately not a second home for the schema-file naming convention,
// whose sole home is the schema package. The assertion below compares bytes
// against bytes; this constant only chooses which bytes to ask for, and never
// decides whether two references agree. Drift in it is loud rather than silent:
// a suffix that stopped matching the distribution leaves the trim a no-op, no
// kind token resolves, and every entry fails at once rather than one quietly
// passing.
const schemaFileSuffix = "-v1alpha1.schema.json"

// TestTargetSchemaFileAgreesWithItsSchemaBytes asserts that the two references
// each target entry carries name the same schema. An entry records its schema
// twice — the embedded bytes the generator reads, and the file name that says
// which schema those bytes are — and nothing compared them.
//
// No other gate here settles a divergence, and the reason is worth stating
// because the first reading of it is the wrong one. The recorded name is emitted
// into the generated file's provenance header, so editing it alone does redden
// the regen-drift gate — the committed file no longer matches. But that gate's
// remedy is to regenerate and commit, and regenerating writes the wrong name
// into the header. Every gate is then green again, permanently, over a published
// generated file that names a schema it was not generated from: the drift gates
// compare the output against the committed file, and the binding-coverage
// assertion above attributes a target by its bytes, so after that one commit
// nothing compares the recorded name with the bytes again.
//
// The name is not decoration. It ships in the provenance header of every
// generated codec, and the generator names it when it refuses to emit, so a
// mismatch misleads a reader of the published file and misleads in the one
// message whose whole job is to say which schema is at fault.
//
// # Both sides of the comparison are bytes, and that is the load-bearing part
//
// The recorded file name is resolved through the schema package's own dynamic
// lookup, and the bytes that lookup returns are compared against the bytes in
// the entry. A file name is never compared with a file name. Deriving the
// expected file name from the kind and matching the two strings would put a
// second copy of the schema-file naming convention here, and a copy that agrees
// today is precisely what hides the divergence it was added to catch — a
// mismatch would then be a string-similarity judgement rather than an
// inequality. That would be worse here than almost anywhere, because this
// assertion's entire subject is two references to one schema disagreeing.
func TestTargetSchemaFileAgreesWithItsSchemaBytes(t *testing.T) {
	// A pass over an empty population certifies nothing, so an emptied table is
	// a failure rather than a green: a table that stopped resolving must not
	// read as "every entry's two references agree".
	if len(enumSources) == 0 || len(codecTargets) == 0 {
		t.Fatalf("enumSources holds %d entries and codecTargets holds %d, so this assertion "+
			"checked nothing: a target table that has stopped resolving cannot report agreement",
			len(enumSources), len(codecTargets))
	}

	// The reverse index is built from the distribution rather than from a hand
	// list, so a failure can name the kind an entry's bytes actually belong to
	// instead of only reporting that they are not the ones named.
	kindByBytes := map[string]string{}
	for _, kind := range schemas.Kinds() {
		body, ok := schemas.SchemaByKind(kind)
		if !ok {
			t.Fatalf("kind %q is enumerated but its schema does not resolve", kind)
		}
		kindByBytes[body] = kind
	}

	check := func(t *testing.T, table, outFile, schemaFile, schemaBody string) {
		t.Helper()
		switch {
		case schemaFile == "" && schemaBody == "":
			// A target generated from no schema at all — the shared codec
			// helpers. Both references are absent together, which is the
			// consistent state for that shape, so there is nothing to compare.
			// This excuses no entry: the case below fails an entry carrying one
			// reference without the other.
			return
		case schemaFile == "":
			t.Errorf("%s[%q] carries schema bytes but records no schemaFile, so nothing says which "+
				"schema those bytes are: a reader, and the generator's own refusal message, have no "+
				"name to report. Record the file the bytes come from.", table, outFile)
			return
		case schemaBody == "":
			t.Errorf("%s[%q] records schemaFile %q but carries no schema bytes, so it names a schema "+
				"it does not generate from.", table, outFile, schemaFile)
			return
		}

		kind := strings.TrimSuffix(schemaFile, schemaFileSuffix)
		want, ok := schemas.SchemaByKind(kind)
		if !ok {
			t.Errorf("%s[%q] records schemaFile %q, whose kind token %q resolves to no schema in the "+
				"distribution. Either the file name is wrong, or the schema it names is no longer "+
				"shipped and the entry is a record of a coupling that has gone.",
				table, outFile, schemaFile, kind)
			return
		}
		if want == schemaBody {
			return
		}
		// Naming the kind the bytes DO belong to turns the failure from "these
		// disagree" into the one edit that fixes it, and it is read from the
		// same distribution rather than guessed.
		actual := "a schema outside the distribution"
		if got, ok := kindByBytes[schemaBody]; ok {
			actual = "the " + got + " schema"
		}
		t.Errorf("%s[%q] records schemaFile %q, but the bytes it generates from are %s. The generated "+
			"output is correct for the bytes, so every drift gate stays green while the entry, and the "+
			"generator's refusal message, name the wrong schema. Correct whichever of the two is wrong.",
			table, outFile, schemaFile, actual)
	}

	for outFile, src := range enumSources {
		t.Run("enumSources/"+outFile, func(t *testing.T) {
			check(t, "enumSources", outFile, src.schemaFile, src.schema)
		})
	}
	for outFile, tgt := range codecTargets {
		t.Run("codecTargets/"+outFile, func(t *testing.T) {
			check(t, "codecTargets", outFile, tgt.schemaFile, tgt.schema)
		})
	}
}

// TestTypeKeywordDecodesBothSpellingsWithoutFlattening drives the real node
// decode over both spellings JSON Schema admits for `type`, and asserts the
// declared set arrives whole.
//
// The flattening is the failure this guards, and it is a silent one. A decode
// that kept only the first member of ["string","number"] would produce a
// generator that compiles, emits, and byte-matches every committed body —
// because no schema registered today spells a set — while quietly asserting
// that an identifier is a string when the wire contract says it is a string or
// a number. Nothing downstream could tell the difference, so the property has
// to be pinned here at the decode.
//
// The rows are driven through decodeNode rather than through the keyword helper
// alone, because the keyword is read in the same pass as every other field and
// it is that pass, not the helper, that a registered target actually runs.
func TestTypeKeywordDecodesBothSpellingsWithoutFlattening(t *testing.T) {
	for _, tc := range []struct {
		name string
		raw  string
		// wantSet is the declared set, joined with "|" so a failure prints what
		// arrived rather than a pair of addresses.
		wantSet  string
		wantOne  string
		wantFail bool
	}{
		{name: "single name", raw: `{"type":"string"}`, wantSet: "string", wantOne: "string"},
		{name: "no type keyword", raw: `{"description":"x"}`, wantSet: "", wantOne: ""},

		// The three spellings the daemon's wire contract actually carries. Each
		// states something true that a narrower reading would discard: a
		// collection emitted as null when it has nothing to report, and an
		// identifier the transport defines as either a string or a number.
		{name: "nullable collection", raw: `{"type":["array","null"]}`, wantSet: "array|null", wantOne: ""},
		{name: "nullable object", raw: `{"type":["object","null"]}`, wantSet: "object|null", wantOne: ""},
		{name: "scalar union", raw: `{"type":["string","number"]}`, wantSet: "string|number", wantOne: ""},

		// Declaration order is part of what the set says, so the reverse
		// spelling must arrive reversed rather than normalised.
		{name: "declaration order is kept", raw: `{"type":["null","array"]}`, wantSet: "null|array", wantOne: ""},

		// A set of one names one type, so it answers the single-name question
		// the same way the single-name spelling does.
		{name: "set of one", raw: `{"type":["string"]}`, wantSet: "string", wantOne: "string"},
		{name: "empty set", raw: `{"type":[]}`, wantSet: "", wantOne: ""},

		// Neither spelling: the decode refuses rather than reading it as absent,
		// which would let a malformed schema generate a file whose fields are
		// all typed `any` and whose emission nothing would question.
		{name: "neither spelling", raw: `{"type":5}`, wantFail: true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got, err := decodeNode(json.RawMessage(tc.raw))
			if tc.wantFail {
				if err == nil {
					t.Fatalf("decodeNode(%s) succeeded; the refusal cannot fire, so it certifies nothing", tc.raw)
				}
				return
			}
			if err != nil {
				t.Fatalf("decodeNode(%s): %v", tc.raw, err)
			}
			if set := strings.Join(got.Types, "|"); set != tc.wantSet {
				t.Errorf("decodeNode(%s) declared set = %q, want %q", tc.raw, set, tc.wantSet)
			}
			if one := got.declaredType(); one != tc.wantOne {
				t.Errorf("decodeNode(%s).declaredType() = %q, want %q", tc.raw, one, tc.wantOne)
			}
		})
	}
}

// TestUnionTypeSurvivesNestingAndNamesNoGoType holds the two consequences of
// carrying a set rather than a name.
//
// Nesting first: the keyword is read by one decode that recurses through
// `properties` and `items`, so a set declared on a leaf has to arrive at that
// leaf and not only at a root the test happens to hand it.
//
// Then the mapping. A set names no one Go type, so every mechanical mapping
// must reach its fall-through arm on one — and the fall-through, not a member
// of the set, is the honest answer. Pinning it here is what would catch a later
// change that makes the mapping pick a member instead of declining: that change
// would move no committed byte, because nothing registered today declares a
// set, so no drift gate would see it.
func TestUnionTypeSurvivesNestingAndNamesNoGoType(t *testing.T) {
	const schema = `{
		"type": "object",
		"properties": {
			"ids": {"type": "array", "items": {"type": ["string", "number"]}},
			"findings": {"type": ["array", "null"], "items": {"type": "string"}}
		}
	}`
	root, err := decodeNode(json.RawMessage(schema))
	if err != nil {
		t.Fatalf("decodeNode: %v", err)
	}
	byName := map[string]schemaNode{}
	for _, p := range root.props {
		byName[p.name] = p.node
	}

	ids, ok := byName["ids"]
	if !ok {
		t.Fatal("the decode dropped the `ids` property")
	}
	if ids.Items == nil {
		t.Fatal("the decode dropped the `ids` items node")
	}
	if set := strings.Join(ids.Items.Types, "|"); set != "string|number" {
		t.Errorf("items node declared set = %q, want %q", set, "string|number")
	}

	findings, ok := byName["findings"]
	if !ok {
		t.Fatal("the decode dropped the `findings` property")
	}
	if set := strings.Join(findings.Types, "|"); set != "array|null" {
		t.Errorf("property node declared set = %q, want %q", set, "array|null")
	}

	// The mapping declines rather than choosing "array" and emitting a slice the
	// schema never promised was always present.
	if got := goType(findings, "Findings", nil); got != "any" {
		t.Errorf("goType on a declared set = %q, want %q", got, "any")
	}

	// The structural refusals are written against a declared object, and a set
	// is not one — so they pass the node through instead of demanding the
	// annotation an object with no properties would need.
	if err := checkFieldNode("schema.json", "#/properties/findings", findings); err != nil {
		t.Errorf("checkFieldNode refused a declared set: %v", err)
	}
	if err := checkElementNode("schema.json", "#/properties/ids/items", *ids.Items); err != nil {
		t.Errorf("checkElementNode refused a declared set: %v", err)
	}
}

// TestOrderedMapValueTypeSpellings covers both ordered-map spellings the
// generator can meet, and asserts them as a pair rather than one at a time
// because only the emission destination decides which one arrives: a codec
// emitted into the package that declares the ordered map sees the bare
// spelling, since a package cannot qualify its own types, while a codec
// emitted anywhere else sees the qualified one.
//
// The pairing is the load-bearing part. A helper that recognises one spelling
// and not the other still emits a codec that compiles and round-trips against
// its own counterpart for the unrecognised form — the map falls through to an
// opaque marshal and is counted as an always-present field — so no compile
// error, no failing round-trip and no drift gate distinguishes the two. The
// equality assertion fixes that one annotation resolves to one value type
// whichever spelling carries it.
func TestOrderedMapValueTypeSpellings(t *testing.T) {
	// The value type is spelling-independent for these, so the bare and
	// qualified forms must agree exactly.
	for _, tc := range []struct {
		name    string
		bare    string
		valType string
	}{
		{name: "scalar value", bare: "OrderedMap[string]", valType: "string"},
		{name: "opaque value", bare: "OrderedMap[json.RawMessage]", valType: "json.RawMessage"},
		{name: "named value", bare: "OrderedMap[IRFeatureEntry]", valType: "IRFeatureEntry"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			qualified := "types." + tc.bare
			gotBare, okBare := orderedMapValueType(tc.bare)
			gotQual, okQual := orderedMapValueType(qualified)
			if !okBare {
				t.Fatalf("orderedMapValueType(%q) reported not-an-ordered-map, so a codec emitted into "+
					"the package that declares the type would encode it opaquely", tc.bare)
			}
			if !okQual {
				t.Fatalf("orderedMapValueType(%q) reported not-an-ordered-map", qualified)
			}
			if gotBare != tc.valType {
				t.Errorf("orderedMapValueType(%q) value type = %q, want %q", tc.bare, gotBare, tc.valType)
			}
			if gotQual != tc.valType {
				t.Errorf("orderedMapValueType(%q) value type = %q, want %q", qualified, gotQual, tc.valType)
			}
			if gotBare != gotQual {
				t.Errorf("the two spellings disagree on the value type: %q yields %q while %q yields %q",
					tc.bare, gotBare, qualified, gotQual)
			}
		})
	}

	// Bracket matching is balanced, so a nested ordered map yields the whole
	// inner ordered map rather than a prefix truncated at the first bracket.
	// The inner spelling is carried through verbatim, which is why these two
	// expectations differ from each other rather than being one value.
	t.Run("nested, bare", func(t *testing.T) {
		got, ok := orderedMapValueType("OrderedMap[OrderedMap[string]]")
		if !ok || got != "OrderedMap[string]" {
			t.Errorf("got (%q, %v), want (%q, true)", got, ok, "OrderedMap[string]")
		}
	})
	t.Run("nested, qualified", func(t *testing.T) {
		got, ok := orderedMapValueType("types.OrderedMap[types.OrderedMap[string]]")
		if !ok || got != "types.OrderedMap[string]" {
			t.Errorf("got (%q, %v), want (%q, true)", got, ok, "types.OrderedMap[string]")
		}
	})

	// Everything that is not an ordered map must still be refused, so widening
	// the accepted spellings does not start claiming plain maps, slices,
	// pointers or scalars as order-preserving containers.
	for _, spelling := range []string{
		"string",
		"json.RawMessage",
		"map[string]string",
		"map[string]OrderedMap[string]",
		"[]string",
		"*CatalogMetadata",
		"other.OrderedMap[string]",
		"OrderedMap[string]trailing",
		"OrderedMap[",
		"",
	} {
		t.Run("refused/"+spelling, func(t *testing.T) {
			if got, ok := orderedMapValueType(spelling); ok {
				t.Errorf("orderedMapValueType(%q) reported an ordered map with value type %q; it is not "+
					"an order-preserving container and encoding it as one would emit a map head for a "+
					"value that has none", spelling, got)
			}
		})
	}
}

// TestCodecOnlyTargetEmitsCodecWithoutDeclarations invokes every codecOnly target
// and reads what it produced, because the properties that make the mode safe are
// invisible in a byte-compare against a committed file: that file could be wrong
// in exactly the same way the generator is.
//
// Three properties, each of which the mode exists to hold. It emits no payload
// declaration, so the destination package keeps its hand-written types and their
// author-chosen field order. It emits no JSON codec, so nothing it adds displaces
// the way those types are already marshalled — a generated MarshalJSON emits
// fields in schema order while the standard library emits them in struct order,
// so installing one moves bytes on paths that reach committed output. And it does
// emit the CBOR codec — one encode entry point per def and two decode entry
// points, the lenient one and the strict one — which is the whole reason the mode
// was wanted: a qualified generated type needs a real generated codec to dispatch
// to.
//
// The declaration check reads the emitted source rather than counting `type`
// keywords blindly: the shared CBOR helpers legitimately declare their own
// reader, and a check that forbade every type declaration would fail on it and
// teach the next reader to loosen the check that matters.
func TestCodecOnlyTargetEmitsCodecWithoutDeclarations(t *testing.T) {
	codecOnlyTargets := map[string]codecTarget{}
	for outFile, tgt := range codecTargets {
		if tgt.codecOnly {
			codecOnlyTargets[outFile] = tgt
		}
	}
	// A pass over an empty population certifies nothing.
	if len(codecOnlyTargets) == 0 {
		t.Fatal("no codecOnly target is registered, so this gate measured nothing")
	}

	for outFile, tgt := range codecOnlyTargets {
		t.Run(outFile, func(t *testing.T) {
			src, err := generateFor(outFile)
			if err != nil {
				t.Fatalf("generate %s: %v", outFile, err)
			}
			body := string(src)

			root, err := decodeNode(json.RawMessage(tgt.schema))
			if err != nil {
				t.Fatalf("decode schema %s: %v", tgt.schemaFile, err)
			}
			if len(root.defs) == 0 {
				t.Fatalf("schema %s declares no defs, so this gate measured nothing", tgt.schemaFile)
			}
			// A target skipping every def would satisfy every assertion below by
			// emitting nothing at all, so the population the gate reads is checked
			// before it is read.
			emittedDefs := 0
			for _, d := range root.defs {
				if tgt.emitsDef(d.name) {
					emittedDefs++
				}
			}
			if emittedDefs == 0 {
				t.Fatalf("%s skips every def schema %s declares, so this gate measured nothing",
					outFile, tgt.schemaFile)
			}

			for _, d := range root.defs {
				if strings.Contains(body, "type "+d.name+" struct {") {
					t.Errorf("%s declares type %s: a codecOnly target must attach to the destination "+
						"package's hand-written declaration, and emitting a second one both duplicates "+
						"it and takes away the field order that declaration was hand-written to keep",
						outFile, d.name)
				}
				for _, method := range []string{
					") EncodeCBOR() ([]byte, error) {",
					") DecodeCBOR(data []byte) error {",
					") DecodeCBORStrict(data []byte) error {",
				} {
					emitted := strings.Contains(body, "func (t "+d.name+method) ||
						strings.Contains(body, "func (t *"+d.name+method)
					// A skipped def is asserted in the opposite direction, and both
					// directions are needed: the absence proves the exclusion took effect,
					// and the presence-for-everything-else proves it took effect only where
					// it was asked for. A one-directional read would accept a skip that
					// swallowed the whole schema.
					if !tgt.emitsDef(d.name) {
						if emitted {
							t.Errorf("%s emits %s for the skipped def %s: the destination package does not "+
								"declare that type, so the emitted codec cannot compile against it",
								outFile, strings.TrimSuffix(strings.TrimPrefix(method, ") "), "() ([]byte, error) {"), d.name)
						}
						continue
					}
					if !emitted {
						t.Errorf("%s emits no %s for %s, so a codec dispatching to that type has nothing "+
							"to call", outFile, strings.TrimSuffix(strings.TrimPrefix(method, ") "), "() ([]byte, error) {"), d.name)
					}
				}
			}

			for _, jsonMethod := range []string{
				") MarshalJSON() ([]byte, error) {",
				") UnmarshalJSON(data []byte) error {",
				") UnmarshalJSONStrict(data []byte) error {",
			} {
				if strings.Contains(body, jsonMethod) {
					t.Errorf("%s emits %s: a codecOnly target's destination package already marshals "+
						"these types, and taking that over changes existing bytes rather than adding a "+
						"transport", outFile, strings.TrimSpace(jsonMethod))
				}
			}
		})
	}
}

