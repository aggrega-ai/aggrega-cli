// TestCBORStrictDecodeEntryPointIsEmittedAndDelegates reads the strict CBOR
// decode entry point out of every Go codec target's emitted source and holds it
// to the three properties that make it what it is, none of which a byte-compare
// against a committed file can see — that file could be wrong in exactly the way
// the generator is.
//
// One: it exists for every def the target emits, because a socket output type
// that lacked it would fall back to the lenient read at the one boundary where
// skipping an unknown key is indistinguishable from a real result.
//
// Two: it DELEGATES. The emitted body runs the key check and then calls the
// type's own DecodeCBOR, so there is one decode implementation per type rather
// than two. A strict body that re-read the map itself would satisfy every
// behavioural assertion while doubling the decode surface, and the second copy
// would drift on exactly the field the first one handles specially.
//
// Three: the declared key list it checks against is the SAME set as the decode
// switch's own case arms. That is the single-source property in the only form
// worth asserting: both lists are emitted from one resolved field slice, so a
// schema field added later moves both, and this gate fails if they ever stop
// agreeing.
func TestCBORStrictDecodeEntryPointIsEmittedAndDelegates(t *testing.T) {
	goTargets := map[string]codecTarget{}
	for outFile, tgt := range codecTargets {
		if tgt.lang == "" || tgt.lang == "go" {
			goTargets[outFile] = tgt
		}
	}
	// A pass over an empty population certifies nothing.
	if len(goTargets) == 0 {
		t.Fatal("no Go codec target is registered, so this gate measured nothing")
	}

	checked := 0
	for outFile, tgt := range goTargets {
		t.Run(outFile, func(t *testing.T) {
			src, err := generateFor(outFile)
			if err != nil {
				t.Fatalf("generate %s: %v", outFile, err)
			}
			body := string(src)

			root, err := decodeNode(json.RawMessage(tgt.schema))
			if err != nil {
				t.Fatalf("decode schema %s: %v", tgt.schemaFile, err)
			}
			emitted := 0
			for _, d := range root.defs {
				if !tgt.emitsDef(d.name) {
					continue
				}
				emitted++
				strictBody, ok := funcBody(body, "func (t *"+d.name+") DecodeCBORStrict(data []byte) error {")
				if !ok {
					t.Errorf("%s emits no DecodeCBORStrict for %s, so a socket reading that shape has no "+
						"entry point that refuses a foreign envelope", outFile, d.name)
					continue
				}
				if !strings.Contains(strictBody, "return t.DecodeCBOR(data)") {
					t.Errorf("%s's DecodeCBORStrict for %s does not delegate to DecodeCBOR: the strict entry "+
						"point must check the keys and then run the one decode body, not carry a second one",
						outFile, d.name)
				}
				if strings.Contains(strictBody, "dec.readMapHeader()") {
					t.Errorf("%s's DecodeCBORStrict for %s reads the map itself: that is a second decode "+
						"implementation for one type, which is what delegating exists to avoid", outFile, d.name)
				}

				declared := refusedKeys(strictBody)
				decodeBody, ok := funcBody(body, "func (t *"+d.name+") decodeCBOR(dec *cborDec) error {")
				if !ok {
					t.Errorf("%s emits no decodeCBOR worker for %s, so the strict entry point's declared key "+
						"set cannot be checked against the shape it guards", outFile, d.name)
					continue
				}
				switched := switchedKeys(decodeBody)
				if !sameKeySet(declared, switched) {
					t.Errorf("%s: %s's strict key list %v differs from its decode switch's own case arms %v; "+
						"the two are emitted from one field slice and disagreeing means a field is guarded "+
						"but not decoded, or decoded but not guarded", outFile, d.name, declared, switched)
				}
			}
			if emitted == 0 {
				t.Fatalf("%s emits no def from schema %s, so this gate measured nothing", outFile, tgt.schemaFile)
			}
			if !strings.Contains(body, "func refuseUndeclaredCBORKeys(") && tgt.helpers {
				t.Errorf("%s is its package's helpers-bearing file but emits no refuseUndeclaredCBORKeys, so "+
					"every DecodeCBORStrict in that package calls a function that is not there", outFile)
			}
			checked += emitted
		})
	}
	if checked == 0 {
		t.Fatal("no def was checked across any Go target, so this gate measured nothing")
	}
}

// funcBody returns the body of the emitted function whose signature line is
// exactly header, from just after that line to the closing brace in column zero.
// Generated Go is gofmt'd, so a lone "}" at column zero is the function's end and
// nothing nested can produce one.
func funcBody(src, header string) (string, bool) {
	i := strings.Index(src, header)
	if i < 0 {
		return "", false
	}
	rest := src[i+len(header):]
	end := strings.Index(rest, "\n}\n")
	if end < 0 {
		return "", false
	}
	return rest[:end], true
}

// refusedKeys extracts the key literals a strict entry point's
// refuseUndeclaredCBORKeys call names.
func refusedKeys(strictBody string) []string {
	const call = "refuseUndeclaredCBORKeys(data"
	i := strings.Index(strictBody, call)
	if i < 0 {
		return nil
	}
	rest := strictBody[i+len(call):]
	end := strings.Index(rest, ")")
	if end < 0 {
		return nil
	}
	return quotedLiterals(rest[:end])
}

// switchedKeys extracts the key literals the decode worker's own field switch
// dispatches on. The anchor is the two-tab indent the field switch's case arms
// carry, which no nested emission produces.
func switchedKeys(decodeBody string) []string {
	var keys []string
	for _, line := range strings.Split(decodeBody, "\n") {
		if !strings.HasPrefix(line, "\t\tcase \"") {
			continue
		}
		keys = append(keys, quotedLiterals(line)...)
	}
	return keys
}

// quotedLiterals returns every double-quoted literal in s, unescaped only for the
// characters a generated schema key can contain.
func quotedLiterals(s string) []string {
	var out []string
	for {
		i := strings.Index(s, `"`)
		if i < 0 {
			return out
		}
		s = s[i+1:]
		j := strings.Index(s, `"`)
		if j < 0 {
			return out
		}
		out = append(out, s[:j])
		s = s[j+1:]
	}
}

// TestInlineObjectIsDeclaredByEveryBackendThatNamesIt pins the whole of what an
// object a property declares inline is worth: a name derived identically at the
// declaration and at the field, and a declaration emitted by every backend whose
// fields carry that name.
//
// It asserts the declaration and the REFERENCE together, per language, because
// either half alone passes while the emitted file is broken. A backend that
// names the type without declaring it emits a module the destination language
// refuses; a backend that declares it under a second name emits a module that
// declares one type and names another. Neither shows up in the generator's own
// sources, and neither is visible to a gate that byte-compares generated files,
// because such a file is stably wrong.
//
// The nested encoder is asserted too, and it is the load-bearing row: a field
// falling through to the opaque arm still type-checks once the declaration
// exists, and it then serialises the value by the key order it was parsed in
// rather than by the order the schema declares — which puts different bytes on
// the wire from the counterpart emission, with nothing failing on either side.
func TestInlineObjectIsDeclaredByEveryBackendThatNamesIt(t *testing.T) {
	const schema = `{
		"$defs": {
			"Capabilities": {
				"type": "object",
				"description": "What the client can handle.",
				"properties": {
					"window": {
						"type": "object",
						"description": "What the client can show.",
						"properties": {
							"progress": {"type": "boolean"},
							"inner": {
								"type": "object",
								"properties": {"depth": {"type": "string"}}
							}
						}
					},
					"named": {"$ref": "#/$defs/Named"},
					"annotated": {
						"type": "object",
						"x-aggrega-go-type": "map[string]string",
						"properties": {"ignored": {"type": "string"}}
					}
				}
			},
			"Named": {"type": "object", "properties": {"value": {"type": "string"}}}
		}
	}`
	target := codecTarget{schema: schema, schemaFile: "probe.schema.json", pkg: "probe", helpers: true}

	tsTarget := target
	tsTarget.lang = "ts"
	tsSrc, err := generateDefs(tsTarget)
	if err != nil {
		t.Fatalf("generateDefs ts: %v", err)
	}
	rustTarget := target
	rustTarget.lang = "rust"
	rustSrc, err := generateDefs(rustTarget)
	if err != nil {
		t.Fatalf("generateDefs rust: %v", err)
	}
	goSrc, err := generateDefs(target)
	if err != nil {
		t.Fatalf("generateDefs go: %v", err)
	}

	for _, tc := range []struct {
		name string
		src  string
		want string
	}{
		// TypeScript: the field names the type, the type is declared, and the
		// encoder dispatches to it rather than carrying it opaquely.
		{"ts field names the derived type", string(tsSrc), "  window?: CapabilitiesWindow;"},
		{"ts declares the derived type", string(tsSrc), "export interface CapabilitiesWindow {"},
		{"ts encodes it structurally", string(tsSrc), "encodeCapabilitiesWindow(v.window)"},
		{"ts emits its encoder", string(tsSrc), "export function encodeCapabilitiesWindow(v: CapabilitiesWindow): string {"},
		{"ts reaches the second level", string(tsSrc), "export interface CapabilitiesWindowInner {"},
		{"ts names the second level", string(tsSrc), "  inner?: CapabilitiesWindowInner;"},
		{"ts carries the CBOR fork too", string(tsSrc), "export function appendCBORCapabilitiesWindow(out: number[], v: CapabilitiesWindow): void {"},

		// Rust: the same pair.
		{"rust field names the derived type", string(rustSrc), "pub window: CapabilitiesWindow,"},
		{"rust declares the derived type", string(rustSrc), "pub struct CapabilitiesWindow {"},
		{"rust reaches the second level", string(rustSrc), "pub struct CapabilitiesWindowInner {"},

		// Go declares it from the struct walk, and the field resolution has to
		// agree with that walk about the name.
		// The type and its tag, rather than the field name beside the type: the
		// formatter pads the column, so a single space between them is a fact
		// about the other fields in the struct rather than about this one.
		{"go field names the derived type", string(goSrc), "CapabilitiesWindow `json:\"window,omitempty\""},
		{"go declares the derived type", string(goSrc), "type CapabilitiesWindow struct {"},
		{"go reaches the second level", string(goSrc), "type CapabilitiesWindowInner struct {"},

		// A node naming its type through a $ref keeps that name, and a node
		// carrying an annotation keeps the annotated one. Neither earns a
		// derived declaration, so both are the boundary of the capability.
		{"a ref keeps the def name", string(tsSrc), "  named?: Named;"},
		{"an annotation keeps its own type", string(tsSrc), "  annotated?: Record<string, string>;"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if !strings.Contains(tc.src, tc.want) {
				t.Errorf("the emitted module does not contain:\n%s", tc.want)
			}
		})
	}

	// The negative controls. A derived declaration under the bare property name
	// is the exact shape the two halves disagreeing produces, and a declaration
	// for a $ref'd or annotated node is a type nothing references.
	for _, absent := range []struct {
		name string
		src  string
		bad  string
	}{
		{"ts must not name the bare property", string(tsSrc), "export interface Window {"},
		{"rust must not name the bare property", string(rustSrc), "pub struct Window {"},
		{"go must not name the bare property", string(goSrc), "type Window struct {"},
		{"ts must not declare a type for a $ref node", string(tsSrc), "export interface CapabilitiesNamed {"},
		{"ts must not declare a type for an annotated node", string(tsSrc), "export interface CapabilitiesAnnotated {"},
	} {
		t.Run(absent.name, func(t *testing.T) {
			if strings.Contains(absent.src, absent.bad) {
				t.Errorf("the emitted module contains a declaration it should not:\n%s", absent.bad)
			}
		})
	}
}

