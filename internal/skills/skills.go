// Package skills carries the assistant skills the aggrega binary ships, and
// writes copies of them where an AI assistant reads skills.
//
// A skill is a folder holding a SKILL.md file in the open Agent Skills format: a
// YAML frontmatter block naming the skill and describing when to use it,
// followed by Markdown instructions. The skills live in this package's source
// tree and are compiled into the binary, so the copy a binary writes is the text
// that matches its own version.
//
// Every copy written from here carries one banner line, which says where the
// copy comes from and that writing the skill again replaces it. The banner is
// what lets a later install tell a copy it wrote, and may replace, from a file
// someone wrote by hand, which it refuses to touch. Two writers produce copies:
// [Install], into an assistant's skill folder, and [WriteRepository], into the
// tree of the public skills repository. Both take their bytes from [Files], so
// an installed copy and a published copy of the same skill are the same bytes.
//
// The published tree is also committed beside this package and regenerated by
// the go:generate directive below; a test in this package fails when the
// committed tree and the embedded skills disagree.
package skills

//go:generate go run ./genrepository -out repository

import (
	"bytes"
	"embed"
	"errors"
	"fmt"
	"io/fs"
	"path"
	"strings"

	"go.yaml.in/yaml/v3"
)

// embedded holds every skill's source folder. A skill is added by adding its
// folder here and its name to skillNames.
//
//go:embed aggrega
var embedded embed.FS

// skillNames are the skills this binary ships, in the order every listing and
// every written tree takes them.
var skillNames = []string{"aggrega"}

// Banner is the line every written copy of a skill file carries.
//
// It names the copy's source so a reader of the published repository or of an
// installed copy can find where to change it, and it says that writing the
// skill again replaces the copy, so nobody keeps an edit in a file that will be
// overwritten. Its exact text is also the mark Install reads to decide whether a
// file at its target is one it may replace, so changing it means an earlier
// copy is no longer recognised: a later install then refuses that copy, naming
// its path, rather than overwriting it.
const Banner = `<!-- Generated from the skill built into the aggrega binary, whose source is ` +
	`github.com/aggrega-ai/aggrega-cli. "aggrega skills install" replaces a copy carrying this line, so keep ` +
	`your own changes in a skill of another name. -->`

// descriptionLimit is the longest description the open skill format admits.
const descriptionLimit = 1024

// Names returns the skills this binary ships, in a fixed order.
func Names() []string {
	return append([]string(nil), skillNames...)
}

// File is one file of a written skill copy, or of the published repository.
type File struct {
	// Path is the file's slash-separated path, relative to the skill's own
	// folder for a skill file and to the repository root for a repository file.
	Path string

	// Content is the bytes written, the banner included.
	Content []byte
}

// Metadata is what a skill's frontmatter declares about it.
type Metadata struct {
	Name        string `yaml:"name"`
	Description string `yaml:"description"`
}

// Describe returns the frontmatter of the named skill, checked against the
// open skill format: a name equal to the skill's folder name, and a description
// of between one and descriptionLimit characters.
func Describe(name string) (Metadata, error) {
	raw, err := fs.ReadFile(embedded, path.Join(name, "SKILL.md"))
	if err != nil {
		return Metadata{}, fmt.Errorf("the %q skill has no SKILL.md: %w", name, err)
	}
	front, _, err := splitFrontmatter(raw)
	if err != nil {
		return Metadata{}, fmt.Errorf("the %q skill's SKILL.md: %w", name, err)
	}
	var meta Metadata
	if err := yaml.Unmarshal(front, &meta); err != nil {
		return Metadata{}, fmt.Errorf("the %q skill's frontmatter does not parse: %w", name, err)
	}
	switch {
	case meta.Name != name:
		return Metadata{}, fmt.Errorf("the %q skill's frontmatter names it %q; the format requires the name of its folder", name, meta.Name)
	case strings.TrimSpace(meta.Description) == "":
		return Metadata{}, fmt.Errorf("the %q skill's frontmatter carries no description", name)
	case len([]rune(meta.Description)) > descriptionLimit:
		return Metadata{}, fmt.Errorf("the %q skill's description is %d characters; the format admits at most %d",
			name, len([]rune(meta.Description)), descriptionLimit)
	}
	return meta, nil
}

// Files returns the files of the named skill as a written copy carries them:
// every file of its folder, in lexical path order, each with the banner.
//
// It refuses a skill whose frontmatter Describe refuses, and a file of a kind
// the banner cannot be written into, so a copy is never written without the mark
// a later install reads.
func Files(name string) ([]File, error) {
	if !shipped(name) {
		return nil, fmt.Errorf("this binary ships no skill named %q", name)
	}
	if _, err := Describe(name); err != nil {
		return nil, err
	}
	sub, err := fs.Sub(embedded, name)
	if err != nil {
		return nil, err
	}
	var out []File
	err = fs.WalkDir(sub, ".", func(p string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			return nil
		}
		raw, err := fs.ReadFile(sub, p)
		if err != nil {
			return err
		}
		content, err := withBanner(p, raw)
		if err != nil {
			return fmt.Errorf("the %q skill's %s: %w", name, p, err)
		}
		out = append(out, File{Path: p, Content: content})
		return nil
	})
	if err != nil {
		return nil, err
	}
	return out, nil
}

// HasBanner reports whether content carries the banner as a line of its own.
func HasBanner(content []byte) bool {
	for _, line := range bytes.Split(content, []byte("\n")) {
		if string(bytes.TrimRight(line, "\r")) == Banner {
			return true
		}
	}
	return false
}

// shipped reports whether name is one of the skills this binary ships.
func shipped(name string) bool {
	for _, n := range skillNames {
		if n == name {
			return true
		}
	}
	return false
}

// withBanner returns content with the banner written into it.
//
// Only Markdown is supported, because the banner is a Markdown comment. A file
// opening with frontmatter takes the banner on the line after the frontmatter's
// closing marker, since the format requires the frontmatter to open the file;
// any other Markdown file takes it as its first line.
func withBanner(p string, content []byte) ([]byte, error) {
	if path.Ext(p) != ".md" {
		return nil, errors.New("only Markdown files can carry the banner a written copy needs")
	}
	if HasBanner(content) {
		return nil, errors.New("the source already carries the banner, which belongs only on a written copy")
	}
	banner := []byte(Banner + "\n")
	if !bytes.HasPrefix(content, []byte("---\n")) {
		return append(banner, content...), nil
	}
	front, rest, err := splitFrontmatter(content)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("---\n")
	b.Write(front)
	b.WriteString("---\n")
	b.Write(banner)
	b.Write(rest)
	return b.Bytes(), nil
}

// splitFrontmatter splits content opening with a "---" line into the
// frontmatter between that line and the next "---" line, and everything after
// the closing line.
func splitFrontmatter(content []byte) (front, rest []byte, err error) {
	const marker = "---\n"
	if !bytes.HasPrefix(content, []byte(marker)) {
		return nil, nil, errors.New("it does not open with a frontmatter block")
	}
	body := content[len(marker):]
	end := bytes.Index(body, []byte("\n"+marker))
	if end < 0 {
		return nil, nil, errors.New("its frontmatter block is never closed")
	}
	return body[:end+1], body[end+1+len(marker):], nil
}
